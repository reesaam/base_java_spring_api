package site.resam.basespringapi.proto.generator;

import java.util.Comparator;
import site.resam.basespringapi.proto.model.ProtoSchema;
import site.resam.basespringapi.proto.model.ProtoSchema.EnumDef;
import site.resam.basespringapi.proto.model.ProtoSchema.EnumValueDef;
import site.resam.basespringapi.proto.model.ProtoSchema.FieldDef;
import site.resam.basespringapi.proto.model.ProtoSchema.MessageDef;
import site.resam.basespringapi.proto.model.ProtoSchema.RpcDef;
import site.resam.basespringapi.proto.model.ProtoSchema.ServiceDef;

/**
 * Renders a {@link ProtoSchema} to a proto3 source file.
 */
public final class ProtoFileWriter {

    public String write(ProtoSchema schema) {
        StringBuilder sb = new StringBuilder();
        sb.append("// AUTO-GENERATED from Java DTOs / service interfaces. DO NOT EDIT.\n");
        sb.append("// Generated by basespringapi-proto-codegen\n");
        sb.append("syntax = \"proto3\";\n\n");
        sb.append("package ").append(schema.getProtoPackage()).append(";\n\n");
        sb.append("option java_multiple_files = true;\n");
        sb.append("option java_package = \"").append(schema.getJavaPackage()).append("\";\n");
        sb.append("option java_outer_classname = \"BaseSpringApiProto\";\n\n");

        schema.getEnums().values().stream()
                .sorted(Comparator.comparing(EnumDef::name))
                .forEach(enumDef -> appendEnum(sb, enumDef));

        schema.getMessages().values().stream()
                .sorted(Comparator.comparing(MessageDef::name))
                .forEach(message -> appendMessage(sb, message));

        schema.getServices().values().stream()
                .sorted(Comparator.comparing(ServiceDef::name))
                .forEach(service -> appendService(sb, service));

        return sb.toString();
    }

    private void appendEnum(StringBuilder sb, EnumDef enumDef) {
        sb.append("enum ").append(enumDef.name()).append(" {\n");
        for (EnumValueDef value : enumDef.values()) {
            sb.append("  ").append(value.name()).append(" = ").append(value.number()).append(";\n");
        }
        sb.append("}\n\n");
    }

    private void appendMessage(StringBuilder sb, MessageDef message) {
        sb.append("message ").append(message.name()).append(" {\n");
        for (FieldDef field : message.fields()) {
            sb.append("  ");
            if (field.repeated()) {
                sb.append("repeated ");
            }
            sb.append(field.type()).append(' ').append(field.name())
                    .append(" = ").append(field.number()).append(";\n");
        }
        sb.append("}\n\n");
    }

    private void appendService(StringBuilder sb, ServiceDef service) {
        sb.append("service ").append(service.name()).append(" {\n");
        for (RpcDef rpc : service.rpcs()) {
            sb.append("  rpc ").append(rpc.name()).append("(").append(rpc.requestType())
                    .append(") returns (").append(rpc.responseType()).append(");\n");
        }
        sb.append("}\n\n");
    }
}
